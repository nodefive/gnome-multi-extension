#!/usr/bin/env bash
# Generate stylesheet.css: the hand-written base plus numbered size classes.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/stylesheet.css"
p=shell-tweaks

{
    cat "$root/stylesheet.base.css"
    echo
    echo "/* generated by tools/gen-stylesheet.sh */"
    for n in $(seq 0 60); do
        echo ".$p-panel-button-padding-size$n .panel-button { -natural-hpadding: ${n}px; -minimum-hpadding: ${n}px; }"
    done
    for n in $(seq 0 60); do
        echo ".$p-panel-indicator-padding-size$n .panel-status-indicators-box { spacing: ${n}px; }"
    done
    for n in $(seq 1 60); do
        echo ".$p-panel-icon-size$n .system-status-icon, .$p-panel-icon-size$n .panel-button StIcon { icon-size: ${n}px; }"
    done
    for n in $(seq 0 60); do
        echo ".$p-workspace-background-radius-size$n .workspace-background { border-radius: ${n}px; }"
    done
    for n in $(seq 1 150); do
        echo ".$p-controls-manager-spacing-size$n .controls-manager, .$p-controls-manager-spacing-size$n .secondary-monitor-workspaces { spacing: ${n}px; }"
    done
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines)"
